using System;
using System.Collections.Generic;
using System.Linq;
using Godot;
using MathRacer.App;

namespace MathRacer.Valley;

/// <summary>
/// The land round the old valley (<c>docs/MAP_EXPANSION_PLAN.md</c>). The core keeps its own grid, which is levelled
/// and graded while the valley is planned; the outland is one grid as fine as the core's up to
/// <see cref="WorldTuning.OutlandRadius"/>, worked out once from the final core, and coarse scenery beyond it up to
/// <see cref="WorldTuning.SceneryRadius"/>. Each chunk of the outland is drawn in full near the camera and every 10 m
/// further away; its collision is made only round the car, since no one else stands there.
/// </summary>
public partial class Terrain
{
    private const float Step = Settings.TerrainStep;

    /// <summary>Cells of the outland grid between its edge and the core's.</summary>
    private static readonly int CoreOffset = Mathf.RoundToInt(
        (WorldTuning.OutlandRadius - WorldTuning.CoreRadius) / Step
    );
    private static readonly int CoreCells = Mathf.RoundToInt(WorldTuning.CoreRadius * 2 / Step);
    private static readonly int OutlandCells = Mathf.RoundToInt(WorldTuning.OutlandRadius * 2 / Step);

    /// <summary>The cells of a chunk along each side, as in the core.</summary>
    private const int ChunkCells = 32;

    /// <summary>A far chunk keeps every fourth point, one every 10 m.</summary>
    private const int FarStride = 4;

    /// <summary>The scenery is a grid of this spacing up to <see cref="WorldTuning.SceneryRadius"/>.</summary>
    private const float SceneryStep = 10;

    /// <summary>
    /// Beyond the scenery a coarser ring of land goes on to the horizon, so that the mountains, the hills and the forest
    /// do not end against the sky. Both radii lie on its grid.
    /// </summary>
    private const float HorizonStep = 25;
    private const float HorizonRadius = 3000;

    /// <summary>Up to this distance a chunk of the outland is drawn in full, beyond it every 10 m.</summary>
    private const float NearRange = 260;

    /// <summary>The far land is drawn in blocks of this many chunks along each side.</summary>
    private const int FarBlockChunks = 4;

    /// <summary>
    /// A far block shows from this distance of its middle, which is nearer than any of its chunks can still be hidden
    /// (NearRange less the 170 m from the middle of a block to the middle of its outer chunks).
    /// </summary>
    private const float FarBegin = 80;

    /// <summary>How much lower the far land lies than the fine ground, which it must not poke through.</summary>
    private const float FarSink = .4f;

    /// <summary>
    /// A coarse piece hangs a skirt this deep from its edges, so that no gap shows where it meets a finer piece.
    /// </summary>
    private const float SkirtDepth = 4;

    /// <summary>Chunks nearer the car than this have collision; it goes again beyond <see cref="ColliderKeep"/>.</summary>
    private const float ColliderReach = 140;
    private const float ColliderKeep = 200;

    private float[,]? outland;

    /// <summary>The roads beyond the old valley, graded into the outland once it is worked out (see <see cref="GradeOutlandRoads"/>).</summary>
    private OutlandRoadbed? outlandRoadbed;

    /// <summary>
    /// The ground as it is before the roads beyond the old valley are graded into it: what they are laid on. Asked once
    /// the old valley stands.
    /// </summary>
    internal float Landscape(float x, float z) =>
        outlandRoadbed == null
            ? RawHeight(x, z)
            : throw new InvalidOperationException("The outland roads are graded already.");

    /// <summary>
    /// Grades the roads beyond the old valley into the outland, which <see cref="BuildMeshes"/> works out next. The old
    /// valley is generated by then and its grid is kept as it is, so this changes nothing in it.
    /// </summary>
    internal void GradeOutlandRoads(OutlandRoadbed roadbed) => outlandRoadbed = roadbed;

    private Node3D? outlandColliders;
    private readonly Dictionary<Vector2I, StaticBody3D> colliders = new();
    private Vector3 colliderFocus = new(float.PositiveInfinity, 0, 0);

    internal int OutlandColliderCount => colliders.Count;
    internal IEnumerable<StaticBody3D> OutlandColliders => colliders.Values;
    internal bool HasOutland => outland != null;

    /// <summary>The height at a point of the core grid outside the core.</summary>
    private float OutlandHeight(int xIndex, int zIndex)
    {
        int x = xIndex + CoreOffset,
            z = zIndex + CoreOffset;
        if (outland != null && x >= 0 && z >= 0 && x <= OutlandCells && z <= OutlandCells)
            return outland[x, z];
        return RawHeight(xIndex * Step - WorldTuning.CoreRadius, zIndex * Step - WorldTuning.CoreRadius);
    }

    private static bool InCore(int cellX, int cellZ) =>
        cellX >= CoreOffset && cellX < CoreOffset + CoreCells && cellZ >= CoreOffset && cellZ < CoreOffset + CoreCells;

    private static bool AllInCore(int startX, int startZ, int endX, int endZ) =>
        startX >= CoreOffset
        && endX <= CoreOffset + CoreCells
        && startZ >= CoreOffset
        && endZ <= CoreOffset + CoreCells;

    private float OutlandAt(int x, int z) => outland![Math.Clamp(x, 0, OutlandCells), Math.Clamp(z, 0, OutlandCells)];

    private void ComputeOutland()
    {
        var grid = new float[OutlandCells + 1, OutlandCells + 1];
        for (int z = 0; z <= OutlandCells; z++)
        for (int x = 0; x <= OutlandCells; x++)
        {
            int coreX = x - CoreOffset,
                coreZ = z - CoreOffset;
            grid[x, z] =
                heights != null && coreX >= 0 && coreZ >= 0 && coreX <= CoreCells && coreZ <= CoreCells
                    ? heights[coreX, coreZ]
                    : RawHeight(x * Step - WorldTuning.OutlandRadius, z * Step - WorldTuning.OutlandRadius);
        }
        outland = grid;
    }

    /// <summary>
    /// Works out the outland and readies its collision, which is streamed round the car. Its meshes only draw it, so
    /// they are built afterwards, a slice at a time (<see cref="BuildOutlandLand"/>, <see cref="DeferredBuild"/>).
    /// </summary>
    private void BuildOutland()
    {
        ulong started = Time.GetTicksMsec();
        ComputeOutland();
        colliders.Clear();
        colliderFocus = new Vector3(float.PositiveInfinity, 0, 0);
        outlandColliders = new Node3D { Name = "OutlandColliders" };
        AddChild(outlandColliders);
        GD.Print(
            $"OUTLAND_READY chunks={NearChunks().Count()} blocks={FarBlocks().Count()} ms={Time.GetTicksMsec() - started}"
        );
    }

    /// <summary>The chunks of the outland grid, in cells, that lie at least partly outside the core.</summary>
    private static IEnumerable<(int StartX, int StartZ, int EndX, int EndZ)> NearChunks()
    {
        for (int startZ = 0; startZ < OutlandCells; startZ += ChunkCells)
        for (int startX = 0; startX < OutlandCells; startX += ChunkCells)
        {
            int endX = Math.Min(startX + ChunkCells, OutlandCells),
                endZ = Math.Min(startZ + ChunkCells, OutlandCells);
            if (!AllInCore(startX, startZ, endX, endZ))
                yield return (startX, startZ, endX, endZ);
        }
    }

    /// <summary>The blocks of the far land, on its grid of every <see cref="FarStride"/>th point.</summary>
    private static IEnumerable<(int StartX, int StartZ, int EndX, int EndZ)> FarBlocks()
    {
        int farCells = OutlandCells / FarStride,
            block = ChunkCells * FarBlockChunks / FarStride;
        for (int startZ = 0; startZ < farCells; startZ += block)
        for (int startX = 0; startX < farCells; startX += block)
        {
            int endX = Math.Min(startX + block, farCells),
                endZ = Math.Min(startZ + block, farCells);
            if (!AllInCore(startX * FarStride, startZ * FarStride, endX * FarStride, endZ * FarStride))
                yield return (startX, startZ, endX, endZ);
        }
    }

    /// <summary>
    /// The meshes of the outland, one at a time: first the far land and the scenery to the horizon, which are seen
    /// from the old valley, then the fine chunks, the nearest to the middle first.
    /// </summary>
    internal IEnumerable<bool> BuildOutlandLand()
    {
        // The far land is drawn in blocks of 4 × 4 chunks, so that it costs few draw calls. A block shows from
        // FarBegin on, before the last of its chunks hides at NearRange, and lies a little lower, so that where both are
        // drawn the fine ground covers the coarse one.
        foreach (var (startX, startZ, endX, endZ) in FarBlocks())
        {
            var center = new Vector3(
                (startX + endX) / 2f * Step * FarStride - WorldTuning.OutlandRadius,
                0,
                (startZ + endZ) / 2f * Step * FarStride - WorldTuning.OutlandRadius
            );
            var far = Patch(
                center,
                -WorldTuning.OutlandRadius,
                Step * FarStride,
                startX,
                startZ,
                endX,
                endZ,
                (x, z) => OutlandAt(x * FarStride, z * FarStride) - FarSink,
                (x, z) => !InCore(x * FarStride, z * FarStride),
                true
            );
            far.VisibilityRangeBegin = FarBegin;
            far.CastShadow = GeometryInstance3D.ShadowCastingSetting.Off;
            yield return true;
        }
        foreach (bool slice in BuildScenery(SceneryStep, WorldTuning.SceneryRadius, WorldTuning.OutlandRadius))
            yield return slice;
        foreach (bool slice in BuildScenery(HorizonStep, HorizonRadius, WorldTuning.SceneryRadius))
            yield return slice;
        static Vector3 Middle((int StartX, int StartZ, int EndX, int EndZ) c) =>
            new(
                (c.StartX + c.EndX) / 2f * Step - WorldTuning.OutlandRadius,
                0,
                (c.StartZ + c.EndZ) / 2f * Step - WorldTuning.OutlandRadius
            );
        foreach (var chunk in NearChunks().OrderBy(chunk => Middle(chunk).LengthSquared()))
        {
            var near = Patch(
                Middle(chunk),
                -WorldTuning.OutlandRadius,
                Step,
                chunk.StartX,
                chunk.StartZ,
                chunk.EndX,
                chunk.EndZ,
                OutlandAt,
                (x, z) => !InCore(x, z),
                false
            );
            near.VisibilityRangeEnd = NearRange;
            yield return true;
        }
    }

    /// <summary>
    /// A ring of coarse land, which is only looked at, between <paramref name="inner"/> and <paramref name="outer"/>
    /// on a grid of <paramref name="step"/>.
    /// </summary>
    private IEnumerable<bool> BuildScenery(float step, float outer, float inner)
    {
        int cells = Mathf.RoundToInt(outer * 2 / step),
            offset = Mathf.RoundToInt((outer - inner) / step),
            hole = Mathf.RoundToInt(inner * 2 / step);
        // One point more on every side, so that the normals at the edge have neighbours.
        var grid = new float[cells + 3, cells + 3];
        for (int z = -1; z <= cells + 1; z++)
        {
            for (int x = -1; x <= cells + 1; x++)
                grid[x + 1, z + 1] = RawHeight(x * step - outer, z * step - outer);
            yield return true;
        }
        float SceneryAt(int x, int z) => grid[Math.Clamp(x, -1, cells + 1) + 1, Math.Clamp(z, -1, cells + 1) + 1];
        bool Outside(int x, int z) => x < offset || x >= offset + hole || z < offset || z >= offset + hole;
        const int piece = 64;
        for (int startZ = 0; startZ < cells; startZ += piece)
        for (int startX = 0; startX < cells; startX += piece)
        {
            int endX = Math.Min(startX + piece, cells),
                endZ = Math.Min(startZ + piece, cells);
            bool any = false;
            for (int z = startZ; z < endZ && !any; z++)
            for (int x = startX; x < endX && !any; x++)
                any = Outside(x, z);
            if (!any)
                continue;
            var center = new Vector3((startX + endX) / 2f * step - outer, 0, (startZ + endZ) / 2f * step - outer);
            var scenery = Patch(center, -outer, step, startX, startZ, endX, endZ, SceneryAt, Outside, true);
            scenery.CastShadow = GeometryInstance3D.ShadowCastingSetting.Off;
            yield return true;
        }
    }

    /// <summary>
    /// A piece of ground on a lattice whose point (i, j) stands at (<paramref name="corner"/> + i ·
    /// <paramref name="spacing"/>, <paramref name="corner"/> + j · <paramref name="spacing"/>) at the given height. The
    /// cells from (i0, j0) to (i1, j1) that <paramref name="filled"/> names are drawn, split into the same triangles as
    /// the core, so that <see cref="Height"/> follows them; a skirt hangs from every edge where no cell of the piece goes
    /// on.
    /// </summary>
    private MeshInstance3D Patch(
        Vector3 center,
        float corner,
        float spacing,
        int i0,
        int j0,
        int i1,
        int j1,
        Func<int, int, float> height,
        Func<int, int, bool> filled,
        bool skirts
    )
    {
        int width = i1 - i0 + 1;
        var vertices = new List<Vector3>();
        var normals = new List<Vector3>();
        var colors = new List<Color>();
        var indices = new List<int>();
        for (int j = j0; j <= j1; j++)
        for (int i = i0; i <= i1; i++)
        {
            float x = corner + i * spacing,
                z = corner + j * spacing;
            float y = height(i, j);
            var normal = new Vector3(
                height(i - 1, j) - height(i + 1, j),
                2 * spacing,
                height(i, j - 1) - height(i, j + 1)
            ).Normalized();
            vertices.Add(new Vector3(x - center.X, y, z - center.Z));
            normals.Add(normal);
            colors.Add(WorldLayout.Plan.Borders.Tint(x, z, y, normal.Y, VertexColor(x, z)));
        }
        int Index(int i, int j) => (j - j0) * width + (i - i0);
        bool Continues(int i, int j) => i >= i0 && i < i1 && j >= j0 && j < j1 && filled(i, j);
        void Skirt(int from, int to)
        {
            int start = vertices.Count;
            foreach (int index in new[] { from, to })
            {
                vertices.Add(vertices[index] + Vector3.Down * SkirtDepth);
                normals.Add(normals[index]);
                colors.Add(colors[index]);
            }
            indices.AddRange(new[] { from, to, start, to, start + 1, start });
        }
        for (int j = j0; j < j1; j++)
        for (int i = i0; i < i1; i++)
        {
            if (!filled(i, j))
                continue;
            int a = Index(i, j),
                b = Index(i + 1, j),
                c = Index(i, j + 1),
                d = Index(i + 1, j + 1);
            indices.AddRange(new[] { a, b, c, b, d, c });
            if (!skirts)
                continue;
            if (!Continues(i, j - 1))
                Skirt(a, b);
            if (!Continues(i + 1, j))
                Skirt(b, d);
            if (!Continues(i, j + 1))
                Skirt(d, c);
            if (!Continues(i - 1, j))
                Skirt(c, a);
        }
        var arrays = new Godot.Collections.Array();
        arrays.Resize((int)Mesh.ArrayType.Max);
        arrays[(int)Mesh.ArrayType.Vertex] = vertices.ToArray();
        arrays[(int)Mesh.ArrayType.Normal] = normals.ToArray();
        arrays[(int)Mesh.ArrayType.Color] = colors.ToArray();
        arrays[(int)Mesh.ArrayType.Index] = indices.ToArray();
        var mesh = new ArrayMesh();
        mesh.AddSurfaceFromArrays(Mesh.PrimitiveType.Triangles, arrays);
        var visual = new MeshInstance3D
        {
            Name = "Outland",
            Mesh = mesh,
            MaterialOverride = meadowMaterial,
            Position = center,
        };
        AddChild(visual);
        return visual;
    }

    /// <summary>
    /// Gives the chunks of the outland round <paramref name="focus"/> (the car) their collision and takes it from those
    /// left far behind. Nothing else touches the ground there, and the core has collision everywhere.
    /// </summary>
    internal void StreamColliders(Vector3 focus)
    {
        if (outland == null || outlandColliders == null)
            return;
        if (FlatMath.Length(focus.X - colliderFocus.X, focus.Z - colliderFocus.Z) < 8)
            return;
        colliderFocus = focus;
        foreach (var key in colliders.Keys.ToList())
            if (ChunkDistance(key, focus) > ColliderKeep)
            {
                colliders[key].QueueFree();
                colliders.Remove(key);
            }
        float size = ChunkCells * Step;
        int chunksPerSide = (OutlandCells + ChunkCells - 1) / ChunkCells;
        int focusX = Mathf.FloorToInt((focus.X + WorldTuning.OutlandRadius) / size),
            focusZ = Mathf.FloorToInt((focus.Z + WorldTuning.OutlandRadius) / size);
        int reach = Mathf.CeilToInt(ColliderReach / size);
        for (int z = Math.Max(0, focusZ - reach); z <= Math.Min(chunksPerSide - 1, focusZ + reach); z++)
        for (int x = Math.Max(0, focusX - reach); x <= Math.Min(chunksPerSide - 1, focusX + reach); x++)
        {
            var key = new Vector2I(x, z);
            if (colliders.ContainsKey(key) || ChunkDistance(key, focus) > ColliderReach)
                continue;
            var body = ChunkCollider(key);
            if (body != null)
                colliders[key] = body;
        }
    }

    private static float ChunkDistance(Vector2I key, Vector3 p)
    {
        float size = ChunkCells * Step;
        float left = key.X * size - WorldTuning.OutlandRadius,
            top = key.Y * size - WorldTuning.OutlandRadius;
        float dx = Math.Max(0, Math.Max(left - p.X, p.X - (left + size))),
            dz = Math.Max(0, Math.Max(top - p.Z, p.Z - (top + size)));
        return FlatMath.Length(dx, dz);
    }

    private StaticBody3D? ChunkCollider(Vector2I key)
    {
        int startX = key.X * ChunkCells,
            startZ = key.Y * ChunkCells,
            endX = Math.Min(startX + ChunkCells, OutlandCells),
            endZ = Math.Min(startZ + ChunkCells, OutlandCells);
        if (AllInCore(startX, startZ, endX, endZ))
            return null;
        var faces = new List<Vector3>();
        Vector3 Point(int x, int z) =>
            new(x * Step - WorldTuning.OutlandRadius, outland![x, z], z * Step - WorldTuning.OutlandRadius);
        for (int z = startZ; z < endZ; z++)
        for (int x = startX; x < endX; x++)
        {
            if (InCore(x, z))
                continue;
            Vector3 a = Point(x, z),
                b = Point(x + 1, z),
                c = Point(x, z + 1),
                d = Point(x + 1, z + 1);
            faces.AddRange(new[] { a, b, c, b, d, c });
        }
        var shape = new ConcavePolygonShape3D();
        shape.SetFaces(faces.ToArray());
        var body = new StaticBody3D { Name = $"Outland{key.X}_{key.Y}" };
        body.AddChild(new CollisionShape3D { Shape = shape });
        outlandColliders!.AddChild(body);
        return body;
    }
}
